# Python Operators

a = 10
b = 3

# Arithmetic Operators
print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)
print("Floor Division:", a // b)
print("Modulus:", a % b)
print("Power:", a ** b)

# Comparison Operators
print("Greater than:", a > b)
print("Equal:", a == b)

# Logical Operators
print("Logical AND:", a > 5 and b < 5)
print("Logical OR:", a < 5 or b < 5)
